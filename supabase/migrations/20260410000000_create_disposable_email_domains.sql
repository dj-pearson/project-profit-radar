-- =============================================
-- Disposable Email Domains Blocklist
-- =============================================
-- Blocks sign-ups from known disposable / throwaway email services.
-- Initial list seeded from:
--   https://github.com/disposable-email-domains/disposable-email-domains
-- Root admins can add, remove, enable/disable entries via the admin UI.
-- =============================================

CREATE TABLE IF NOT EXISTS disposable_email_domains (
  id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  domain      TEXT NOT NULL UNIQUE,
  is_active   BOOLEAN NOT NULL DEFAULT true,
  source      TEXT NOT NULL DEFAULT 'seed'
              CHECK (source IN ('seed', 'manual', 'import')),
  notes       TEXT,
  created_by  UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Normalize domain on insert/update (lowercased, trimmed)
CREATE OR REPLACE FUNCTION normalize_disposable_email_domain()
RETURNS TRIGGER AS $$
BEGIN
  NEW.domain = lower(trim(NEW.domain));
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER disposable_email_domains_normalize
  BEFORE INSERT OR UPDATE ON disposable_email_domains
  FOR EACH ROW EXECUTE FUNCTION normalize_disposable_email_domain();

-- Index for fast lookups during sign-up validation
CREATE INDEX IF NOT EXISTS idx_disposable_email_domains_domain_active
  ON disposable_email_domains (domain)
  WHERE is_active = true;

CREATE INDEX IF NOT EXISTS idx_disposable_email_domains_created_at
  ON disposable_email_domains (created_at DESC);

-- =============================================
-- Row Level Security
-- =============================================

ALTER TABLE disposable_email_domains ENABLE ROW LEVEL SECURITY;

-- Only root_admin can read the blocklist directly from the client.
-- Sign-up validation runs through a SECURITY DEFINER function so
-- anonymous users never need SELECT access to the table.
CREATE POLICY "Root admins can read disposable email domains"
  ON disposable_email_domains FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM user_profiles
      WHERE user_profiles.id = auth.uid()
        AND user_profiles.role = 'root_admin'
    )
  );

CREATE POLICY "Root admins can insert disposable email domains"
  ON disposable_email_domains FOR INSERT
  TO authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM user_profiles
      WHERE user_profiles.id = auth.uid()
        AND user_profiles.role = 'root_admin'
    )
  );

CREATE POLICY "Root admins can update disposable email domains"
  ON disposable_email_domains FOR UPDATE
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM user_profiles
      WHERE user_profiles.id = auth.uid()
        AND user_profiles.role = 'root_admin'
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM user_profiles
      WHERE user_profiles.id = auth.uid()
        AND user_profiles.role = 'root_admin'
    )
  );

CREATE POLICY "Root admins can delete disposable email domains"
  ON disposable_email_domains FOR DELETE
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM user_profiles
      WHERE user_profiles.id = auth.uid()
        AND user_profiles.role = 'root_admin'
    )
  );

-- Service role (used by signup-with-otp and other edge functions) has full access
CREATE POLICY "Service role full access disposable email domains"
  ON disposable_email_domains FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

-- =============================================
-- Lookup function
-- =============================================
-- SECURITY DEFINER so anonymous sign-up callers can check a domain
-- without being granted direct SELECT on the table.
CREATE OR REPLACE FUNCTION is_disposable_email_domain(p_email TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_domain TEXT;
  v_exists BOOLEAN;
BEGIN
  IF p_email IS NULL OR position('@' in p_email) = 0 THEN
    RETURN false;
  END IF;

  v_domain := lower(split_part(p_email, '@', 2));

  IF v_domain = '' THEN
    RETURN false;
  END IF;

  SELECT EXISTS (
    SELECT 1 FROM disposable_email_domains
    WHERE domain = v_domain AND is_active = true
  ) INTO v_exists;

  RETURN v_exists;
END;
$$;

GRANT EXECUTE ON FUNCTION is_disposable_email_domain(TEXT) TO anon, authenticated, service_role;

